// 정규방정식 (A^T A + lam I) w = A^T y 를 가우스 소거로 푼다. 원문 파이썬 코드와 같은 순서의 계산이다.
export function fit(xs, ys, deg, lam) {
  const n = deg + 1;
  const A = xs.map((x) => Array.from({length: n}, (_, k) => Math.pow(x, k)));
  const M = [];
  for (let i = 0; i < n; i += 1) {
    const row = [];
    for (let j = 0; j < n; j += 1) {
      let s = 0;
      A.forEach((r) => {
        s += r[i] * r[j];
      });
      row.push(s + (i === j ? lam : 0));
    }
    let t = 0;
    A.forEach((r, q) => {
      t += r[i] * ys[q];
    });
    row.push(t);
    M.push(row);
  }
  for (let i = 0; i < n; i += 1) {
    let p = i;
    for (let r = i; r < n; r += 1) if (Math.abs(M[r][i]) > Math.abs(M[p][i])) p = r;
    const tmp = M[i];
    M[i] = M[p];
    M[p] = tmp;
    for (let r = 0; r < n; r += 1) {
      if (r !== i) {
        const f = M[r][i] / M[i][i];
        M[r] = M[r].map((a, c) => a - f * M[i][c]);
      }
    }
  }
  return Array.from({length: n}, (_, i) => M[i][n] / M[i][i]);
}

export const poly = (w, x) => w.reduce((s, c, k) => s + c * Math.pow(x, k), 0);

export const mse = (w, xs, ys) => {
  let s = 0;
  xs.forEach((x, i) => {
    s += Math.pow(poly(w, x) - ys[i], 2);
  });
  return s / xs.length;
};
